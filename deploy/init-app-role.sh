#!/bin/sh
set -eu
psql --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" --set=app_password="$SHOP_APP_PASSWORD" --set=ON_ERROR_STOP=1 <<'SQL'
CREATE ROLE shop_app LOGIN PASSWORD :'app_password';
GRANT CONNECT ON DATABASE shop TO shop_app;
GRANT USAGE ON SCHEMA public TO shop_app;
ALTER DEFAULT PRIVILEGES FOR ROLE shop IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO shop_app;
ALTER DEFAULT PRIVILEGES FOR ROLE shop IN SCHEMA public GRANT USAGE, SELECT ON SEQUENCES TO shop_app;
SQL
